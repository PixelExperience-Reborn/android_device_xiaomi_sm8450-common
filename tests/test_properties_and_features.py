"""vendor.prop, odm.prop and the hardware features of sm8450-common.

The properties come from the stock OS3.0.8.0.VMNCNXM vendor/build.prop and
odm/etc/build.prop, keeping only what the shipped components and AOSP read.
These tests keep out what the Android 17 build system generates and what
only MIUI reads, and check the Android 17 GRF and feature wiring.
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Values the Android 17 build system generates for vendor/odm: setting them
# again would conflict with the generated build.prop.
GENERATED = re.compile(
    r"^(ro\.(vendor|odm)\.build\.|ro\.product\.|ro\.vendor\.product\.|ro\.odm\.product\."
    r"|ro\.board\.|ro\.bionic\.|ro\.build\.|dalvik\.vm\.isa\.|persist\.sys\.dalvik\.vm\.lib"
    r"|ro\.apex\.updatable|ro\.boot\.|ro\.virtual_ab\.|ro\.zygote|ro\.vndk\.|ro\.adb\.secure"
    r"|ro\.control_privapp|ro\.minui\.|external_storage\.|ro\.sf\.lcd_density)")
# Read only by MIUI framework/apps or by services this build does not ship.
MIUI_ONLY = re.compile(
    r"(millet|beluga|mi_sf|dolby|karaoke|tencent|youme|richtap|^sys\.haptic|aiasst"
    r"|dc_backlight|^sys\.displayfeature|^ro\.vendor\.displayfeature|^persist\.sys\.miui"
    r"|^ro\.miui|^ro\.rom\.zone|^ro\.gfx\.driver|^vendor\.media\.vpp|^ro\.hardware\.camera$"
    r"|^persist\.vendor\.(night\.charge|domain\.charge|dpm\.))", re.I)
REQUIRED = {
    "ro.hardware.egl": "adreno",
    "ro.hardware.vulkan": "adreno",
    "ro.opengles.version": "196610",
    "ro.soc.manufacturer": "QTI",
    "ro.soc.model": "SM8475",
    "ro.telephony.default_network": "33,33",
    "persist.radio.multisim.config": "dsds",
}


def read_props(name):
    props = {}
    for n, line in enumerate((ROOT / name).read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep or not key or key != key.strip():
            raise AssertionError(f"{name}:{n}: not key=value: {line!r}")
        if key in props:
            raise AssertionError(f"{name}:{n}: {key} set twice")
        props[key] = value
    return props


class PropertiesTest(unittest.TestCase):
    def setUp(self):
        self.vendor = read_props("vendor.prop")
        self.odm = read_props("odm.prop")

    def test_required_values(self):
        for key, value in REQUIRED.items():
            self.assertEqual(self.vendor.get(key), value, key)

    def test_no_generated_or_miui_only_properties(self):
        for key in list(self.vendor) + list(self.odm):
            self.assertIsNone(GENERATED.match(key), f"{key} is generated by the build")
            self.assertIsNone(MIUI_ONLY.search(key), f"{key} is read only by MIUI")

    def test_vendor_and_odm_do_not_overlap(self):
        self.assertFalse(set(self.vendor) & set(self.odm))

    def test_board_config_wires_the_files(self):
        board = (ROOT / "BoardConfigCommon.mk").read_text()
        self.assertIn("TARGET_VENDOR_PROP += $(COMMON_PATH)/vendor.prop", board)
        self.assertIn("TARGET_ODM_PROP += $(COMMON_PATH)/odm.prop", board)
        self.assertNotRegex(board, r"(?m)^\s*BOARD_API_LEVEL\s*:?=",
                            "Android 17 sets BOARD_API_LEVEL itself")


class FeaturesTest(unittest.TestCase):
    def setUp(self):
        self.common = (ROOT / "common.mk").read_text()

    def test_grf_vendor_api_level(self):
        self.assertRegex(self.common, r"(?m)^BOARD_SHIPPING_API_LEVEL := 31$")

    def test_features_come_from_frameworks_native_once(self):
        copies = re.findall(r"frameworks/native/data/etc/([\w.\-]+\.xml):"
                            r"\$\(TARGET_COPY_OUT_VENDOR\)/etc/permissions/([\w.\-]+\.xml)",
                            self.common)
        self.assertGreater(len(copies), 20)
        targets = [t for _, t in copies]
        self.assertEqual(len(targets), len(set(targets)), "a feature file is copied twice")
        for src, dst in copies:
            # Versioned sources install under the unversioned feature name.
            self.assertTrue(dst == src or src.startswith(dst[:-len(".xml")]), (src, dst))

    def test_hal_dependent_features_wait_for_their_hals(self):
        # Declared by the device together with the NFC, IR and fingerprint HALs:
        # ConsumerIrService, for one, aborts system_server without its HAL.
        for feature in ("consumerir", "fingerprint", "nfc"):
            self.assertNotIn(f"android.hardware.{feature}", self.common)

    def test_keymint_v1_feature(self):
        self.assertIn("android.hardware.hardware_keystore_V1.xml", self.common)


if __name__ == "__main__":
    unittest.main()
