"""Bring-up vendor SELinux policy (sepolicy/vendor).

Generated by tools/gen_bringup_sepolicy.py from the stock OS3.0.8.0 policy.
Every service the shipped init scripts start needs a domain transition (init
refuses it otherwise, even permissive); every context entry needs a declared
type. Permissive is for userdebug/eng only.
"""
import os
import re
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sibling(*names):
    for base in (ROOT.parent, ROOT / ".ci"):
        for name in names:
            if (base / name).is_dir():
                return base / name
    return None


DEVICE = sibling("mondrian", "android_device_xiaomi_mondrian")
TREES = [ROOT] + ([DEVICE] if DEVICE else [])
# Types of the AOSP 17 platform policy the contexts use.
AOSP = re.compile(r"^(hal_\w+_default_exec|hal_\w+_hwservice|rild_exec|tee_exec|mediacodec_exec)$")


def declared():
    types = set()
    for tree in TREES:
        te = tree / "sepolicy/vendor/bringup.te"
        if te.exists():
            types |= set(re.findall(r"(?m)^type ([\w-]+)", te.read_text()))
    return types


class SepolicyTest(unittest.TestCase):
    def test_context_types_are_declared(self):
        types = declared()
        for tree in TREES:
            for name in ("file_contexts", "hwservice_contexts", "service_contexts"):
                for line in (tree / "sepolicy/vendor" / name).read_text().splitlines():
                    if not line.strip() or line.startswith("#"):
                        continue
                    ctype = line.split()[-1].split(":")[2]
                    with self.subTest(tree=tree.name, line=line):
                        self.assertTrue(ctype in types or AOSP.match(ctype), ctype)

    def test_platform_scripts_and_daemons_have_domains(self):
        te = (ROOT / "sepolicy/vendor/bringup.te").read_text()
        fc = (ROOT / "sepolicy/vendor/file_contexts").read_text()
        for domain in ("vendor_qti_init_shell", "vendor_pd_mapper", "vendor_per_mgr", "vendor_qrtr",
                       "vendor_wcnss_service", "vendor_hal_keymint_qti", "vendor_hal_gatekeeper_qti",
                       "vendor_sensors", "vendor_adsprpcd", "vendor_cdsprpcd", "qti_display_boot"):
            self.assertIn(f"init_daemon_domain({domain})", te)
        self.assertIn("domain_auto_trans(init, vendor_shell_exec, vendor_qti_init_shell)", te)
        for path in ("init\\.qti\\.qcv\\.sh", "init\\.class_main\\.sh", "init\\.qti\\.kernel\\.sh",
                     "hw/qcrilNrd", "qseecomd"):
            self.assertIn(path, fc)
        self.assertNotIn("allow ", te)

    def test_permissive_only_off_user_builds(self):
        board = "\n".join(l for l in (ROOT / "BoardConfigCommon.mk").read_text().splitlines()
                          if not l.lstrip().startswith("#"))
        self.assertIn("BOARD_VENDOR_SEPOLICY_DIRS += $(COMMON_PATH)/sepolicy/vendor", board)
        self.assertRegex(board, r"ifneq \(\$\(TARGET_BUILD_VARIANT\),user\)\n"
                                r"BOARD_BOOTCONFIG \+= androidboot\.selinux=permissive\nendif")
        self.assertNotIn("selinux=permissive", re.sub(r"ifneq \(\$\(TARGET_BUILD_VARIANT\),user\)\n"
                                                      r"BOARD_BOOTCONFIG \+= androidboot\.selinux=permissive\nendif",
                                                      "", board))
        if DEVICE:
            self.assertIn("BOARD_VENDOR_SEPOLICY_DIRS += $(DEVICE_PATH)/sepolicy/vendor",
                          (DEVICE / "BoardConfig.mk").read_text())

    def test_generated_files_are_current(self):
        stock, aosp = os.environ.get("PE_STOCK_ROOT"), os.environ.get("PE_AOSP_SEPOLICY")
        if not (stock and aosp):
            self.skipTest("set PE_STOCK_ROOT (extracted OTA) and PE_AOSP_SEPOLICY (system/sepolicy)")
        subprocess.run([sys.executable, str(ROOT / "tools/gen_bringup_sepolicy.py"), "--stock", stock,
                        "--aosp", aosp, "--check"], check=True)


if __name__ == "__main__":
    unittest.main()
