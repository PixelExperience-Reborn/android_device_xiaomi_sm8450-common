#!/usr/bin/env python3
"""Generate the bring-up vendor SELinux policy of the device trees.

The first boot runs SELinux permissive (userdebug only, see BoardConfig): init
still refuses to start a service whose executable has no domain transition,
and the HAL service managers need context entries. This tool writes, from the
stock OS3.0.8.0 compiled policy (vendor/etc/selinux of the official OTA), only
what the services this build ships need:

* the domain and executable types the stock policy defines (with the HAL
  server attributes it gives them), the transitions from init, and the
  vendor shell transition of the platform scripts;
* the stock file contexts of their executables;
* the stock hwservice/service contexts of the HALs our VINTF manifests declare;
* the file types our fstabs and init scripts mount with ``context=`` (the modem,
  bluetooth and qmcs partitions). A mount with a context the policy does not
  declare fails with EINVAL even permissive, which would leave the ADSP, CDSP,
  modem and IPA firmware of /vendor/firmware_mnt unmounted.

Types the AOSP 17 platform policy already defines are not redeclared. Allow
rules are not generated, except the stock ``associate`` of a mount context type
with itself: they come from the denials of the device, before SELinux is
switched to enforcing.

Usage: gen_bringup_sepolicy.py --stock <extracted OTA root> --aosp <system/sepolicy>
       [--check]
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by tools/gen_bringup_sepolicy.py from the stock OS3.0.8.0 policy; do not edit.\n"


def sibling(*names):
    for base in (ROOT.parent, ROOT / ".ci"):
        for name in names:
            if (base / name).is_dir():
                return base / name
    return None


def listed(tree):
    out = []
    for line in (tree / "proprietary-files.txt").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            out.append(line.split("|")[0].split(";")[0].lstrip("-"))
    return out


def aosp_types(aosp):
    types = set()
    for d in ("public", "vendor"):
        for f in (aosp / d).glob("*.te"):
            text = f.read_text()
            types.update(re.findall(r"(?m)^\s*type\s+(\w+)", text))
    return types


def aosp_contexts(aosp, name):
    keys = set()
    for f in [aosp / "private" / name, aosp / "vendor" / name]:
        if f.exists():
            for line in f.read_text().splitlines():
                line = line.strip()
                if line and not line.startswith("#"):
                    keys.add(line.split()[0])
    return keys


class Stock:
    def __init__(self, root):
        sel = root / "vendor/etc/selinux"
        self.cil = (sel / "vendor_sepolicy.cil").read_text()
        self.types = set(re.findall(r"(?m)^\(type (\S+)\)", self.cil))
        self.attrs = {}
        for attr, members in re.findall(r"(?m)^\(typeattributeset (\S+) \(([^)]*)\)\)", self.cil):
            for m in members.split():
                self.attrs.setdefault(m, set()).add(attr)
        self.trans = {}
        for src, exe, dom in re.findall(r"(?m)^\(typetransition (\S+) (\S+) process (\S+)\)", self.cil):
            if src.split("_31_0")[0] == "init":
                self.trans[exe.replace("_31_0", "")] = dom
        self.fc = []
        for line in (sel / "vendor_file_contexts").read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                self.fc.append((line.split()[0], line.split()[-1], line))
        self.hwsc = {}
        for line in (sel / "vendor_hwservice_contexts").read_text().splitlines():
            parts = line.split()
            if len(parts) == 2 and not parts[0].startswith("#"):
                self.hwsc[parts[0]] = parts[1].split(":")[2]
        self.sc = {}
        for line in (sel / "vendor_service_contexts").read_text().splitlines():
            parts = line.split()
            if len(parts) == 2 and not parts[0].startswith("#"):
                self.sc[parts[0]] = parts[1].split(":")[2]

    def label(self, path):
        hit = None
        for rx, ctx, line in self.fc:
            try:
                if re.fullmatch(rx, path):
                    hit = (ctx, line)
            except re.error:
                pass
        return hit


def services(tree, stock_root, files):
    found = []
    rcs = [(p, (stock_root / p).read_text(errors="replace")) for p in files if p.endswith(".rc")]
    rcs += [(str(f), f.read_text()) for f in (tree / "rootdir").rglob("*.rc")]
    for name, text in rcs:
        for m in re.finditer(r"(?m)^service\s+(\S+)\s+(\S+)([^\n]*)\n((?:[ \t]+[^\n]*\n?)*)", text):
            svc, exe, args, body = m.groups()
            if not exe.startswith(("/vendor/", "/system/vendor/", "/odm/")):
                continue
            sl = re.search(r"(?m)^\s+seclabel\s+u:r:(\S+):s0", body)
            script = args.split()[0] if exe.endswith("/sh") and args.split() else None
            found.append((exe.replace("/system/vendor/", "/vendor/"), sl[1] if sl else None, script))
        for m in re.finditer(r"exec(?:_background|_start)?\s+u:r:(\S+):s0\s+--\s+(\S+)", text):
            found.append((m[2], m[1], None))
    return found


MOUNT_ATTRS = ("file_type", "fs_type", "contextmount_type", "vendor_file_type", "data_file_type")


def mount_contexts(tree):
    """Types named by context= mount options in the tree's fstabs and init scripts."""
    found = []
    for f in sorted((tree / "rootdir").rglob("*")):
        if f.is_file() and (f.suffix == ".rc" or "fstab" in f.name):
            for line in f.read_text(errors="replace").splitlines():
                if not line.lstrip().startswith("#"):
                    for t in re.findall(r"context=u:object_r:(\w+):s0", line):
                        if t not in found:
                            found.append(t)
    return found


def manifest_hals(tree):
    out = []
    path = tree / "vintf/manifest.xml"
    if path.exists():
        for hal in ET.parse(path).getroot().findall("hal"):
            fmt, name = hal.get("format", "hidl"), hal.findtext("name")
            for fq in hal.findall("fqname"):
                out.append((fmt, name, fq.text))
    return out


def generate(tree, stock, stock_root, aosp, platform_types, aosp_fc, aosp_hwsc, aosp_sc):
    files = listed(tree)
    te, fcl, hwl, scl = [], [], [], []
    declared = set()

    def declare(t, kind):
        if t in platform_types or t in declared or t not in stock.types:
            return
        declared.add(t)
        if kind == "exec":
            te.append(f"type {t}, exec_type, vendor_file_type, file_type;")
        elif kind == "domain":
            te.append(f"type {t}, domain;")
            for attr in sorted(stock.attrs.get(t, ())):
                m = re.fullmatch(r"(hal_\w+)_server", attr)
                if m:
                    te.append(f"hal_server_domain({t}, {m[1]})")
        elif kind == "hwservice":
            te.append(f"type {t}, hwservice_manager_type;")
        elif kind == "service":
            extra = [a for a in ("hal_service_type", "protected_service") if a in stock.attrs.get(t, ())]
            te.append(f"type {t}, {', '.join(['service_manager_type'] + extra)};")
        elif kind == "mount":
            attrs = [a for a in MOUNT_ATTRS if a in stock.attrs.get(t, ())]
            te.append(f"type {t}, {', '.join(attrs)};")
            if re.search(rf"(?m)^\(allow {t} self \(filesystem \(associate\)\)\)", stock.cil):
                te.append(f"allow {t} self:filesystem associate;")

    done_paths = set()
    for exe, seclabel, script in services(tree, stock_root, files):
        for path in [p for p in (exe, script) if p]:
            if path in done_paths or path.lstrip("/") not in files and not path.startswith("/vendor/bin/sh"):
                continue
            hit = stock.label(path)
            if not hit:
                continue
            done_paths.add(path)
            ctx, line = hit
            etype = ctx.split(":")[2]
            if etype == "vendor_shell_exec":
                continue
            declare(etype, "exec")
            if line.split()[0] not in aosp_fc and line not in fcl:
                fcl.append(line)
            dom = seclabel or stock.trans.get(etype)
            if dom:
                declare(dom, "domain")
                if stock.trans.get(etype) == dom and (dom in declared or etype in declared):
                    rule = f"init_daemon_domain({dom})"
                    if rule not in te:
                        te.append(rule)
        if exe == "/vendor/bin/sh":
            dom = stock.trans.get("vendor_shell_exec")
            declare(dom, "domain")
            rule = f"domain_auto_trans(init, vendor_shell_exec, {dom})"
            if rule not in te:
                te.append(rule)
        elif seclabel:
            declare(seclabel, "domain")
    for t in mount_contexts(tree):
        declare(t, "mount")
    for fmt, name, fq in manifest_hals(tree):
        if fmt == "hidl":
            m = re.fullmatch(r"@[\d.]+::(\w+)/.+", fq)
            key = f"{name}::{m[1]}"
            if key in aosp_hwsc or key not in stock.hwsc:
                continue
            declare(stock.hwsc[key], "hwservice")
            line = f"{key} u:object_r:{stock.hwsc[key]}:s0"
        else:
            iface, inst = fq.split("/", 1)
            key = f"{name}.{iface}/{inst}"
            if key in aosp_sc or key not in stock.sc:
                continue
            declare(stock.sc[key], "service")
            line = f"{key} u:object_r:{stock.sc[key]}:s0"
        if line not in (hwl if fmt == "hidl" else scl):
            (hwl if fmt == "hidl" else scl).append(line)
    out = tree / "sepolicy/vendor"
    return {
        out / "bringup.te": HEADER + "\n".join(te) + "\n",
        out / "file_contexts": HEADER + "\n".join(sorted(fcl)) + "\n",
        out / "hwservice_contexts": HEADER + "\n".join(sorted(hwl)) + "\n",
        out / "service_contexts": HEADER + "\n".join(sorted(scl)) + "\n",
    }


def main():
    cli = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    cli.add_argument("--stock", type=Path, required=True)
    cli.add_argument("--aosp", type=Path, required=True)
    cli.add_argument("--check", action="store_true", help="fail if the committed files differ")
    args = cli.parse_args()
    stock = Stock(args.stock)
    types = aosp_types(args.aosp)
    fc_keys = aosp_contexts(args.aosp, "file_contexts")
    hw_keys = aosp_contexts(args.aosp, "hwservice_contexts")
    sc_keys = aosp_contexts(args.aosp, "service_contexts")
    trees = [ROOT] + [t for t in [sibling("mondrian", "android_device_xiaomi_mondrian")] if t]
    common_out = {}
    stale = []
    for tree in trees:
        outputs = generate(tree, stock, args.stock, args.aosp, types | set(common_out), fc_keys, hw_keys, sc_keys)
        # Types the common tree declares are not redeclared by the device tree.
        common_out.update({t: 1 for f, text in outputs.items() if f.name == "bringup.te"
                           for t in re.findall(r"(?m)^type (\w+)", text)})
        for path, text in outputs.items():
            if args.check:
                if not path.exists() or path.read_text() != text:
                    stale.append(str(path))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if stale:
        sys.exit("stale: " + ", ".join(stale))


if __name__ == "__main__":
    main()
